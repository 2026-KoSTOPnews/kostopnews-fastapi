def sentiment_prompt(company, title, content):
    return f"""
당신은 금융 뉴스를 분석하는 AI입니다.

목표:
아래 기사를 읽고 기업 "{company}"의 기업 가치에 미치는 영향을 분석하세요.

분석 기준:
- 반드시 기업 "{company}"의 관점에서 판단하세요.
- 기사 전체의 분위기가 아니라 해당 기업의 가치에 미치는 영향을 평가하세요.
- 기사 내용이 "{company}"와 직접 관련이 없거나 영향이 불명확하면 neutral로 판단하세요.
- 추측이나 투자 의견이 아니라 기사에 근거하여 판단하세요.

분석 순서:
1. 기사가 "{company}"에 미치는 영향을 분석합니다.
2. 영향의 방향과 강도를 0.00~1.00 사이의 실수(score)로 평가합니다.
3. score를 기준으로 sentiment를 결정합니다.

sentiment 규칙:
- score > 0.55 → positive
- 0.45 <= score <= 0.55 → neutral
- score < 0.45 → negative

기사 제목:
{title}

기사 본문:
{content}

다음 JSON 형식으로만 응답하세요.

{{
  "summary": "기사 핵심 사실을 2~3문장으로 요약",
  "sentiment": "positive | neutral | negative",
  "score": 0.00,
  "reason": "감성 판단 핵심 이유"
}}

score 기준:
- score는 0.00~1.00 사이의 실수입니다.
- 소수 둘째 자리까지 작성하세요.
- score는 "{company}"의 기업 가치에 미치는 영향의 방향과 강도를 나타냅니다.
- 영향이 매우 크면 0.00 또는 1.00에 가까운 값을 사용하세요.
- 영향이 약하거나 불확실하면 0.50에 가까운 값을 사용하세요.
- 아래 숫자는 예시일 뿐이며, 기사 내용에 맞게 0.00~1.00 사이의 어떤 값이라도 사용할 수 있습니다.

예시:
- 0.97 : 매우 강한 호재
- 0.84 : 강한 호재
- 0.71 : 긍정적
- 0.58 : 약한 긍정
- 0.50 : 중립
- 0.43 : 약한 부정
- 0.29 : 부정적
- 0.11 : 매우 부정적
- 0.03 : 치명적인 악재

작성 규칙:
- summary는 객관적인 사실만 2~3문장으로 요약하세요.
- reason은 score를 부여한 가장 핵심적인 근거만 20자 이내로 작성하세요.
- JSON 외의 다른 설명이나 Markdown은 출력하지 마세요.
"""

def keyword_prompt(title: str, content: str) -> str:
    return f"""
다음 뉴스 기사를 분석하여 기사의 핵심 이슈를 나타내는 태그를 추출하세요.

[제목]
{title}

[본문]
{content}

다음 규칙을 반드시 지키세요.

1. 태그는 기사에서 가장 중요한 이슈, 사건, 기술, 제품, 사업, 산업, 정책, 시장 등을 나타내야 합니다.
2. 단순히 본문에 등장하는 단어나 일반적인 단어는 태그로 추출하지 마세요.
3. 기업명은 태그에서 제외하세요.
4. 인명과 지역명은 기사에서 핵심 이슈를 나타내는 경우가 아니라면 제외하세요.
5. 기사에서 부수적으로 언급되는 내용은 제외하세요.
6. 서로 의미가 중복되거나 유사한 태그는 하나로 통합하세요.
7. 태그만 보고도 해당 기사의 주요 이슈를 파악할 수 있도록 구체적으로 작성하세요.
8. 태그는 짧고 명확한 명사 또는 명사구 형태로 작성하세요.
9. 태그 개수를 고정하지 마세요. 기사에서 핵심 이슈를 나타내는 데 필요한 태그만 추출하세요.
10. 핵심 이슈가 적다면 적은 수의 태그만 추출하고, 중요하지 않은 태그를 억지로 추가하지 마세요.
11. 최종적으로 기사 전체를 대표할 수 있는 핵심 태그만 남기세요.
12. 반드시 JSON 형식으로만 응답하세요.

응답 형식:
{{
    "keywords": [
        "핵심 태그1",
        "핵심 태그2"
    ]
}}
"""